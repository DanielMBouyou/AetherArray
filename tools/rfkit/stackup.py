def permittivity_for_phase_deg(st: Stackup, key: str, limit_deg: float,
                               theta_deg: float = LONGEST_STATE_DEG) -> float:
    """Largest substrate permittivity error keeping ``theta_deg`` within ``limit_deg``."""
    c = st.construction(key)
    s = seed(st, key)
    p = _nominal(c)

    def err(d):
        ee = line(p["h"], p["er"] + d, s["w_seed_m"], p["t"], tand=p["tand"],
                  sigma=p["sigma"]).eeff
        return phase_error_deg(theta_deg, s["eeff"], ee) - limit_deg
    return float(brentq(err, 0.0, 0.5 * p["er"], xtol=1e-6))


