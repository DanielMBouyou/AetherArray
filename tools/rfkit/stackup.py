def sim001_parameters(st: Stackup, key: str = "beamformer") -> dict:
    """Every number the SIM-001 model needs, generated from the canonical file.

    Lengths are those of a two line pair whose difference is a quarter guided
    wavelength at f0, so that the same pair, as a coupon, extracts the
    propagation constant over 1 to 3 GHz without approaching a half wavelength
    singularity. Port and box sizes are starting values that SIM-001 itself
    checks by enlarging them; they are not sacred.
    """
    c = st.construction(key)
    s = seed(st, key)
    w, h, t = s["w_seed_m"], c.h.si, c.t.si
    #: The short line is long enough for the port's evanescent modes to die out
    #: many times over, at about fifty substrate heights; the long one adds a
    #: quarter guided wavelength, rounded to 0.1 mm.
    l_short = 10e-3
    l_long = l_short + round(0.25 * s["lambda_g_m"] * 1e4) / 1e4
    sm = st.simulation_model
    return {
        "task": "SIM-001",
        "stackup": st.fingerprint,
        "construction": key,
        "label": "W values are seeds; SIM-001 decides the 50 ohm width",
        "variables_mm": {
            "sub_h": round(h * 1e3, 6),
            "cu_t": round(t * 1e3, 6),
            "w_seed": round(w * 1e3, 4),
            "l_short": round(l_short * 1e3, 3),
            "l_long": round(l_long * 1e3, 3),
            "port_w": round(max(10 * w, w + 10 * h) * 1e3, 3),
            "port_h": round(10 * h * 1e3, 3),
        },
        "width_sweep_mm": [round(w * k * 1e3, 4) for k in SIM001_SETTINGS["width_factors"]],
        "materials": {
            "substrate": {"permittivity": c.er.value, "loss_tangent": c.tand.value,
                          "permittivity_status": c.er.status, "source": c.er.source},
            "copper": {"conductivity_s_per_m": c.sigma.si, "status": c.sigma.status},
        },
        "model_choices": {k: v.get("model", v.get("value")) if isinstance(v, dict) else v
                          for k, v in sm.items()},
        "settings": dict(SIM001_SETTINGS),
    }


