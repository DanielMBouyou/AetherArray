"""The Rev A stack-up, read from one canonical file by every tool.

Decision 0009 selects the stack-up. Its numbers live in exactly one place,
``hardware/rev-a/stackup/reva-stackup.json``, and everything else reads them
from there: this module, the SIM-001 geometry, any PyAEDT or ADS set-up, and the
tables in the documentation, which are generated by ``python -m rfkit.cli
stackup --markdown`` and checked by the tests.

Three rules, each the reason this module exists:

- **Every number carries its unit, its status and its source.** The status is
  one of ``guaranteed`` (a published fabrication or laminate specification
  limit), ``typical`` (a laminate vendor's typical value), ``nominal`` (a value a
  design tool or a fabricator's calculator uses) or ``assumed`` (an engineering
  assumption, named in decision 0009). A typical value is never read as a
  tolerance.
- **Nominal and tolerance are kept apart.** A construction holds nominal values
  only. Tolerances sit in their own block, as bounds with no distribution,
  because no source gives statistics. A bound nobody publishes is
  ``unbounded``, with no number, rather than guessed.
- **Nothing here freezes RF geometry.** Every width and length computed below is
  a seed for SIM-001 or a feasibility estimate, and is labelled so. The
  canonical file may not hold a trace width, a line length or a patch
  dimension, and the tests enforce it.

The line model is scikit-rf's ``MLine``: Hammerstad and Jensen for the
quasi-static impedance and effective permittivity, with their finite thickness
correction, and Kirschning and Jansen for dispersion. The dielectric is held
frequency invariant at the stated value, smooth copper is assumed, and both
choices are recorded in the canonical file's ``simulation_model`` block.
"""
from __future__ import annotations

import hashlib
import itertools
import json
import math
import re
import warnings
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np
import skrf
from scipy.constants import c as C0
from scipy.constants import mu_0 as MU0
from scipy.optimize import brentq
from skrf.media import MLine

from .budget import F0_HZ

REPO = Path(__file__).resolve().parents[2]
CANONICAL_PATH = REPO / "hardware" / "rev-a" / "stackup" / "reva-stackup.json"
#: Alternatives decision 0009 compared and did not select. Evidence only.
CANDIDATES_PATH = REPO / "hardware" / "rev-a" / "stackup" / "candidates.json"
SCHEMA = "aetherarray-stackup/1"

#: The four kinds of value the task separates, and nothing else.
STATUSES = ("guaranteed", "typical", "nominal", "assumed")
#: A tolerance bound may also be absent, which is said rather than guessed.
BOUND_STATUSES = STATUSES + ("unbounded",)

#: Units a quantity may carry, and their factor to SI.
UNITS = {"m": 1.0, "mm": 1e-3, "um": 1e-6, "Hz": 1.0, "MHz": 1e6, "GHz": 1e9,
         "S/m": 1.0, "1": 1.0}

QUANTITY_KEYS = {"value", "unit", "status", "source", "frequency_hz", "method", "note"}
BOUND_KEYS = {"parameter", "kind", "minus", "plus", "unit", "status", "source", "basis", "note"}

#: The model input each tolerance perturbs. All four are reserved for every
#: construction, bounded or not, so a tolerance study never silently skips one.
TOLERANCE_PARAMETERS = {
    "rf_dielectric_thickness": "h",
    "rf_dielectric_permittivity": "er",
    "rf_copper_thickness": "t",
    "etched_width": "w",
}

#: Key names that would freeze RF geometry if they appeared in the canonical
#: file. Geometry is decided by SIM-001 and at layout, never by the stack-up.
FROZEN_GEOMETRY = re.compile(
    r"^(trace_?width|w_?50(_seed)?|w_?70(_7)?|line_?length|delay_?length|"
    r"patch_?(length|width)|l_?patch|w_?patch|feed_?(offset|inset|position)|"
    r"element_?spacing)$",
    re.I,
)

NP_TO_DB = 20.0 / math.log(10.0)  # 8.686 dB per neper, field quantities

#: Bits of the switched line phase shifter, decision 0003, and their sum, the
#: longest differential delay any channel can carry.
BIT_DEG = (45.0, 90.0, 180.0)
LONGEST_STATE_DEG = sum(BIT_DEG)

#: Element spacing used only to size the antenna board for a feasibility check:
#: half the free space wavelength at f0, as published by decision 0004. Not a
#: design value of this module and never written back anywhere.
SPACING_FOR_SIZE_CHECK_M = 0.5 * C0 / F0_HZ


class StackupError(ValueError):
    """The canonical file is malformed, or breaks one of the rules above."""


# ----------------------------------------------------------------- data model
@dataclass(frozen=True)
class Quantity:
    """One number with its unit, its status and where it came from."""

    value: float
    unit: str
    status: str
    source: str
    frequency_hz: float | None = None
    method: str = ""
    note: str = ""

    @property
    def si(self) -> float:
        return self.value * UNITS[self.unit]


@dataclass(frozen=True)
class Bound:
    """A min-max tolerance on one model input, with no distribution."""

    key: str
    parameter: str
    kind: str          # "relative" (fraction of nominal) or "absolute"
    minus: float | None
    plus: float | None
    unit: str
    status: str
    source: str
    basis: str = ""
    note: str = ""

    @property
    def bounded(self) -> bool:
        return self.status != "unbounded"

    def interval(self, nominal_si: float) -> tuple[float, float]:
        """Low and high values in SI. Raises if the bound is not known."""
        if not self.bounded:
            raise StackupError(f"tolerance {self.key} is unbounded: {self.note}")
        if self.kind == "relative":
            return nominal_si * (1.0 - self.minus), nominal_si * (1.0 + self.plus)
        k = UNITS[self.unit]
        return nominal_si - self.minus * k, nominal_si + self.plus * k


@dataclass(frozen=True)
class Construction:
    """One board's build, as the selected fabrication process defines it."""

    key: str
    raw: dict
    materials: dict

    @property
    def board(self) -> str:
        return self.raw["board"]

    @property
    def layers(self) -> list[dict]:
        return self.raw["layers"]

    def layer(self, name: str) -> dict:
        for layer in self.layers:
            if layer["name"] == name:
                return layer
        raise StackupError(f"{self.key}: no layer named {name}")

    @property
    def rf(self) -> dict:
        return self.raw["rf_line"]

    def _q(self, d: dict) -> Quantity:
        return Quantity(**d)

    @property
    def substrate_layers(self) -> list[dict]:
        return [self.layer(n) for n in self.rf["substrate_layers"]]

    @property
    def substrate_material(self) -> dict:
        names = {layer["material"] for layer in self.substrate_layers}
        if len(names) != 1:
            raise StackupError(f"{self.key}: the RF substrate mixes materials {sorted(names)}")
        return self.materials[names.pop()]

    @property
    def h(self) -> Quantity:
        """Dielectric thickness between the RF trace and its reference plane."""
        layers = self.substrate_layers
        if len(layers) != 1:
            raise StackupError(f"{self.key}: expected one substrate layer under the RF trace")
        return self._q(layers[0]["thickness"])

    @property
    def er(self) -> Quantity:
        return self._q(self.substrate_material["permittivity"])

    @property
    def tand(self) -> Quantity:
        return self._q(self.substrate_material["loss_tangent"])

    @property
    def t(self) -> Quantity:
        """Finished copper thickness of the RF signal layer."""
        return self._q(self.layer(self.rf["signal_layer"])["thickness"])

    @property
    def sigma(self) -> Quantity:
        cu = self.materials[self.layer(self.rf["signal_layer"])["material"]]
        return self._q(cu["conductivity"])

    @property
    def finished_thickness(self) -> Quantity:
        return self._q(self.raw["finished_thickness"])


@dataclass(frozen=True)
class Stackup:
    raw: dict
    path: Path | None = None
    sha256: str | None = None
    constructions: dict = field(default_factory=dict)
    tolerances: dict = field(default_factory=dict)

    @property
    def id(self) -> str:
        return self.raw["id"]

    @property
    def fingerprint(self) -> str:
        """Identifier plus content hash, carried by every trace built on it.

        The identifier alone would survive an edit that forgot to bump the
        revision; the hash does not.
        """
        return f"{self.id}:{(self.sha256 or 'in-memory')[:12]}"

    @property
    def simulation_model(self) -> dict:
        return self.raw["simulation_model"]

    def construction(self, key: str) -> Construction:
        try:
            return self.constructions[key]
        except KeyError:
            raise StackupError(f"no construction {key!r}; have {sorted(self.constructions)}")


# ----------------------------------------------------------------- validation
def _is_number(x) -> bool:
    return isinstance(x, (int, float)) and not isinstance(x, bool) and math.isfinite(x)


def _check_quantity(d: dict, where: str, sources: dict, problems: list) -> None:
    extra = set(d) - QUANTITY_KEYS
    if extra:
        problems.append(f"{where}: keys {sorted(extra)} do not belong in a nominal quantity "
                        "(tolerances go in the tolerances block)")
    for k in ("value", "unit", "status", "source"):
        if k not in d:
            problems.append(f"{where}: missing {k}")
    if "value" in d and not _is_number(d["value"]):
        problems.append(f"{where}: value must be a finite number")
    if d.get("unit") not in UNITS:
        problems.append(f"{where}: unit {d.get('unit')!r} is not one of {sorted(UNITS)}")
    if d.get("status") not in STATUSES:
        problems.append(f"{where}: status {d.get('status')!r} is not one of {STATUSES}")
    if d.get("source") not in sources:
        problems.append(f"{where}: source {d.get('source')!r} is not in the sources block")
    if d.get("frequency_hz") is not None and not _is_number(d["frequency_hz"]):
        problems.append(f"{where}: frequency_hz must be a number or null")


def _walk(node, where: str, sources: dict, problems: list) -> None:
    if isinstance(node, dict):
        for k in node:
            if FROZEN_GEOMETRY.match(str(k)):
                problems.append(f"{where}.{k}: RF geometry may not be frozen in the stack-up")
        if "value" in node:
            _check_quantity(node, where, sources, problems)
            return
        for k, v in node.items():
            _walk(v, f"{where}.{k}", sources, problems)
    elif isinstance(node, list):
        for i, v in enumerate(node):
            name = v.get("name", i) if isinstance(v, dict) else i
            _walk(v, f"{where}[{name}]", sources, problems)


def _check_bound(key: str, d: dict, where: str, sources: dict, problems: list) -> None:
    extra = set(d) - BOUND_KEYS
    if extra:
        problems.append(f"{where}: keys {sorted(extra)} are not allowed; bounds carry no "
                        "distribution and no nominal value")
    if d.get("parameter") != TOLERANCE_PARAMETERS.get(key):
        problems.append(f"{where}: parameter must be {TOLERANCE_PARAMETERS.get(key)!r}")
    if d.get("kind") not in ("relative", "absolute"):
        problems.append(f"{where}: kind must be relative or absolute")
    if d.get("unit") not in UNITS:
        problems.append(f"{where}: unit {d.get('unit')!r} is not one of {sorted(UNITS)}")
    if d.get("kind") == "relative" and d.get("unit") != "1":
        problems.append(f"{where}: a relative bound is a fraction, unit '1'")
    if d.get("status") not in BOUND_STATUSES:
        problems.append(f"{where}: status {d.get('status')!r} is not one of {BOUND_STATUSES}")
    if d.get("source") not in sources:
        problems.append(f"{where}: source {d.get('source')!r} is not in the sources block")
    if d.get("status") == "unbounded":
        if d.get("minus") is not None or d.get("plus") is not None:
            problems.append(f"{where}: an unbounded tolerance carries no number")
        if not d.get("note"):
            problems.append(f"{where}: an unbounded tolerance must say how it will be bounded")
    else:
        for side in ("minus", "plus"):
            if not _is_number(d.get(side)) or d[side] < 0:
                problems.append(f"{where}: {side} must be a non-negative number")


def validate(raw: dict) -> list[str]:
    """Every rule the canonical file must satisfy. Empty means valid."""
    problems: list[str] = []
    if raw.get("schema") != SCHEMA:
        problems.append(f"schema must be {SCHEMA!r}")
    for k in ("id", "revision", "status", "date", "decision", "sources", "materials",
              "constructions", "tolerances", "simulation_model"):
        if k not in raw:
            problems.append(f"missing top level key {k}")
    if problems:
        return problems
    sources = raw["sources"]
    for sid, s in sources.items():
        for k in ("title", "kind", "consulted"):
            if not s.get(k):
                problems.append(f"sources.{sid}: missing {k}")
        if s.get("kind") in ("fabricator", "laminate_vendor") and not s.get("url"):
            problems.append(f"sources.{sid}: a vendor source needs a url")
    for section in ("materials", "constructions", "simulation_model"):
        _walk(raw[section], section, sources, problems)
    for name, choice in raw["simulation_model"].items():
        if choice.get("status") not in STATUSES or choice.get("source") not in sources:
            problems.append(f"simulation_model.{name}: needs a status and a known source")
        if not choice.get("model"):
            problems.append(f"simulation_model.{name}: needs a model")
    for key, cons in raw["constructions"].items():
        names = [layer.get("name") for layer in cons.get("layers", [])]
        rf = cons.get("rf_line", {})
        for role in ("signal_layer", "reference_layer"):
            if rf.get(role) not in names:
                problems.append(f"constructions.{key}.rf_line.{role} names no layer")
        for name in rf.get("substrate_layers", []):
            if name not in names:
                problems.append(f"constructions.{key}.rf_line.substrate_layers: {name} is no layer")
        if rf.get("signal_layer") in names and rf.get("reference_layer") in names:
            i, j = names.index(rf["signal_layer"]), names.index(rf["reference_layer"])
            between = names[min(i, j) + 1:max(i, j)]
            if between != rf.get("substrate_layers"):
                problems.append(f"constructions.{key}: the RF reference plane is not the next "
                                "copper layer; substrate_layers must be exactly the layers between")
        for layer in cons.get("layers", []):
            if layer.get("material") not in raw["materials"]:
                problems.append(f"constructions.{key}: layer {layer.get('name')} has unknown "
                                f"material {layer.get('material')!r}")
        bounds = raw["tolerances"].get(key)
        if bounds is None:
            problems.append(f"tolerances.{key}: missing; every construction reserves its bounds")
            continue
        for tkey in TOLERANCE_PARAMETERS:
            if tkey not in bounds:
                problems.append(f"tolerances.{key}.{tkey}: reserved parameter missing")
        for tkey, d in bounds.items():
            if tkey not in TOLERANCE_PARAMETERS:
                problems.append(f"tolerances.{key}.{tkey}: unknown tolerance")
                continue
            _check_bound(tkey, d, f"tolerances.{key}.{tkey}", sources, problems)
    return problems


def _build(raw: dict, path: Path | None, sha: str | None) -> Stackup:
    problems = validate(raw)
    if problems:
        raise StackupError("invalid stack-up:\n  " + "\n  ".join(problems))
    cons = {k: Construction(key=k, raw=v, materials=raw["materials"])
            for k, v in raw["constructions"].items()}
    tols = {k: {tk: Bound(key=tk, **{f: d.get(f) for f in BOUND_KEYS if f in d})
                for tk, d in v.items()}
            for k, v in raw["tolerances"].items()}
    return Stackup(raw=raw, path=path, sha256=sha, constructions=cons, tolerances=tols)


def load(path: Path | str | None = None) -> Stackup:
    """Read and validate the canonical stack-up. Raises :class:`StackupError`."""
    path = Path(path) if path is not None else CANONICAL_PATH
    data = path.read_bytes()
    raw = json.loads(data.decode("utf-8"))
    return _build(raw, path, hashlib.sha256(data).hexdigest())


def from_dict(raw: dict) -> Stackup:
    """Validate an in-memory stack-up, for tests and candidate comparisons."""
    return _build(raw, None, None)


def load_candidates(path: Path | str | None = None) -> Stackup:
    """The rejected alternatives, validated by the same rules. Never simulated."""
    return load(path if path is not None else CANDIDATES_PATH)


# ----------------------------------------------------------------- line model
@dataclass(frozen=True)
class Line:
    """Microstrip properties at one frequency, from the scikit-rf model."""

    w_m: float
    f_hz: float
    z0_ohm: float
    eeff: float
    alpha_c_db_per_m: float
    alpha_d_db_per_m: float

    @property
    def lambda_g_m(self) -> float:
        return C0 / (self.f_hz * math.sqrt(self.eeff))

    @property
    def alpha_db_per_m(self) -> float:
        return self.alpha_c_db_per_m + self.alpha_d_db_per_m


def line(h_m: float, er: float, w_m: float, t_m: float, f_hz: float = F0_HZ,
         tand: float = 0.0, sigma: float = 5.8e7) -> Line:
    """Hammerstad and Jensen with Kirschning and Jansen dispersion, smooth copper."""
    freq = skrf.Frequency.from_f([f_hz], unit="Hz")
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        m = MLine(frequency=freq, w=w_m, h=h_m, t=t_m, ep_r=er, tand=tand,
                  rho=1.0 / sigma, rough=0.0, model="hammerstadjensen",
                  disp="kirschningjansen", diel="frequencyinvariant", z0_port=50.0)
        return Line(
            w_m=w_m, f_hz=f_hz,
            z0_ohm=float(np.real(m.z0_characteristic[0])),
            eeff=float(np.real(m.ep_reff_f[0])),
            alpha_c_db_per_m=float(np.real(m.alpha_conductor[0])) * NP_TO_DB,
            alpha_d_db_per_m=float(np.real(m.alpha_dielectric[0])) * NP_TO_DB,
        )


def solve_width(z0_ohm: float, h_m: float, er: float, t_m: float, f_hz: float = F0_HZ,
                tand: float = 0.0, sigma: float = 5.8e7) -> float:
    """Width at which the model's characteristic impedance equals ``z0_ohm``."""
    def err(w):
        return line(h_m, er, w, t_m, f_hz, tand, sigma).z0_ohm - z0_ohm
    return float(brentq(err, 0.01 * h_m, 40.0 * h_m, xtol=1e-10))


def closed_form_width(z0_ohm: float, er: float, h_m: float) -> float:
    """Wheeler and Hammerstad synthesis, zero thickness, quasi-static.

    Pozar, Microwave Engineering, 4th edition, equation 3.197. An independent
    check on :func:`solve_width`, not a second answer.
    """
    a = z0_ohm / 60.0 * math.sqrt((er + 1) / 2) + (er - 1) / (er + 1) * (0.23 + 0.11 / er)
    w_over_h = 8 * math.exp(a) / (math.exp(2 * a) - 2)
    if w_over_h > 2:
        b = 377 * math.pi / (2 * z0_ohm * math.sqrt(er))
        w_over_h = 2 / math.pi * (b - 1 - math.log(2 * b - 1) + (er - 1) / (2 * er)
                                  * (math.log(b - 1) + 0.39 - 0.61 / er))
    return w_over_h * h_m


def filling_factor(h_m: float, w_m: float) -> float:
    """``F`` in the quasi-static effective permittivity, Pozar equation 3.195."""
    return 1.0 / math.sqrt(1.0 + 12.0 * h_m / w_m)


def closed_form_eeff(er: float, h_m: float, w_m: float) -> float:
    return (er + 1) / 2 + (er - 1) / 2 * filling_factor(h_m, w_m)


def phase_error_deg(theta_deg: float, eeff_design: float, eeff_actual: float) -> float:
    """Error of an electrical length laid out for one permittivity, realised on another.

    Exact for a uniform line: the physical length is fixed, so the realised
    phase scales with the square root of the effective permittivity.
    """
    return theta_deg * (math.sqrt(eeff_actual / eeff_design) - 1.0)


def first_order_phase_error_deg(theta_deg: float, er: float, h_m: float, w_m: float,
                                d_er: float) -> float:
    """The same error to first order in the substrate permittivity, quasi-static.

    ``d phi / phi = (1/2) d eeff / eeff`` and ``d eeff / d er = (1 + F) / 2``.
    """
    f = filling_factor(h_m, w_m)
    return 0.5 * theta_deg * (1 + f) / 2 * d_er / closed_form_eeff(er, h_m, w_m)


# ----------------------------------------------------------------- derived, non-final
def _nominal(c: Construction) -> dict:
    return {"h": c.h.si, "er": c.er.value, "t": c.t.si, "tand": c.tand.value,
            "sigma": c.sigma.si}


def seed(st: Stackup, key: str, z0_ohm: float = 50.0, f_hz: float = F0_HZ) -> dict:
    """A width seed for SIM-001 and what follows from it. **Initialisation only.**

    The returned width is ``W_seed``, not the final width. SIM-001 decides the
    width; layout takes it from SIM-001, never from here.
    """
    c = st.construction(key)
    p = _nominal(c)
    w = solve_width(z0_ohm, p["h"], p["er"], p["t"], f_hz, p["tand"], p["sigma"])
    ln = line(p["h"], p["er"], w, p["t"], f_hz, p["tand"], p["sigma"])
    wcf = closed_form_width(z0_ohm, p["er"], p["h"])
    return {
        "label": "INITIALISATION ONLY: W_seed is not the final width; SIM-001 decides it",
        "construction": key, "stackup": st.fingerprint, "z0_target_ohm": z0_ohm, "f_hz": f_hz,
        "w_seed_m": w, "w_closed_form_m": wcf,
        "w_seed_vs_closed_form": w / wcf - 1.0,
        "eeff": ln.eeff, "eeff_closed_form": closed_form_eeff(p["er"], p["h"], w),
        "lambda0_m": C0 / f_hz, "lambda_g_m": ln.lambda_g_m,
        "length_for_deg_m": {f"{d:g}": d / 360.0 * ln.lambda_g_m
                             for d in BIT_DEG + (LONGEST_STATE_DEG,)},
        "alpha_c_db_per_m": ln.alpha_c_db_per_m, "alpha_d_db_per_m": ln.alpha_d_db_per_m,
        "model": "scikit-rf MLine: hammerstadjensen, kirschningjansen, frequency invariant "
                 "dielectric, smooth copper",
    }


#: Lead pitch of the SC-70-6 package the PE4259-63 comes in, decision 0003. A 50
#: ohm line much wider than this needs a taper at every one of the 87 switch RF
#: pins, and each taper is one more discontinuity to model.
SC70_PITCH_M = 0.65e-3


def width_flags(st: Stackup, key: str, w_m: float) -> list[str]:
    """Fabrication and layout sanity of a line width. Empty means unremarkable."""
    c = st.construction(key)
    rules = c.raw.get("rules", {})
    flags = []
    if "min_trace" in rules:
        wmin = Quantity(**rules["min_trace"]).si
        if w_m < 2 * wmin:
            flags.append(f"narrow: under twice the {wmin * 1e3:.3f} mm process minimum")
    if "beamformer" in c.board and w_m > SC70_PITCH_M:
        flags.append("wide: over the SC-70-6 lead pitch, a taper at every switch pin")
    return flags


def sensitivity(st: Stackup, key: str, w_m: float | None = None,
                f_hz: float = F0_HZ) -> dict:
    """One at a time and all-corner effect of each bounded tolerance.

    Evaluated at the seed width with every other input nominal. The phase is the
    error of a line laid out for the nominal effective permittivity, for each
    bit and for the longest state. Bounds only: no statistics are implied, so
    the combined figure is the worst corner, not a root sum of squares.
    """
    c = st.construction(key)
    p = _nominal(c)
    if w_m is None:
        w_m = seed(st, key, f_hz=f_hz)["w_seed_m"]
    p["w"] = w_m
    base = line(p["h"], p["er"], w_m, p["t"], f_hz, p["tand"], p["sigma"])
    thetas = BIT_DEG + (LONGEST_STATE_DEG,)

    def evaluate(q):
        ln = line(q["h"], q["er"], q["w"], q["t"], f_hz, q["tand"], q["sigma"])
        return {"z0_ohm": ln.z0_ohm, "eeff": ln.eeff,
                "phase_error_deg": {f"{d:g}": phase_error_deg(d, base.eeff, ln.eeff)
                                    for d in thetas}}

    rows, intervals, unbounded = {}, {}, []
    for tkey, b in st.tolerances[key].items():
        name = b.parameter
        if not b.bounded:
            unbounded.append(tkey)
            continue
        lo, hi = b.interval(p[name])
        intervals[name] = (lo, hi)
        rows[tkey] = {"status": b.status, "low": evaluate({**p, name: lo}),
                      "high": evaluate({**p, name: hi})}
    corners = []
    names = sorted(intervals)
    for combo in itertools.product(*(intervals[n] for n in names)):
        corners.append(evaluate({**p, **dict(zip(names, combo))}))
    worst = {f"{d:g}": max(abs(r["phase_error_deg"][f"{d:g}"]) for r in corners)
             for d in thetas} if corners else {}
    z0s = [r["z0_ohm"] for r in corners]
    return {"construction": key, "w_m": w_m, "nominal": {"z0_ohm": base.z0_ohm, "eeff": base.eeff},
            "one_at_a_time": rows, "unbounded": unbounded,
            "worst_corner_phase_error_deg": worst,
            "z0_range_ohm": (min(z0s), max(z0s)) if z0s else None}


def state_loss_spread_db(st: Stackup, key: str, roughness_factor: float = 1.0,
                         f_hz: float = F0_HZ) -> float:
    """Extra loss of the longest switched line state over the shortest.

    The delay arms of all three bits add ``315/360`` of a guided wavelength. The
    loss of that extra length is a state dependent amplitude, which the diagonal
    state cannot absorb. ``roughness_factor`` multiplies conductor loss only.
    """
    s = seed(st, key, f_hz=f_hz)
    alpha = s["alpha_c_db_per_m"] * roughness_factor + s["alpha_d_db_per_m"]
    return alpha * s["length_for_deg_m"][f"{LONGEST_STATE_DEG:g}"]


def patch_sanity(st: Stackup, key: str, f_hz: float = F0_HZ) -> dict:
    """Order of magnitude rectangular patch figures. **Sanity check only.**

    Transmission line model, Balanis, Antenna Theory, equations 14-1, 14-2, 14-6
    and 14-7, and the Jackson and Alexopoulos bandwidth estimate. None of these
    is a design value: the patch is optimised in HFSS later and its length,
    width, feed and spacing stay free parameters until then.
    """
    c = st.construction(key)
    h, er, tand, sigma = c.h.si, c.er.value, c.tand.value, c.sigma.si
    lam0 = C0 / f_hz
    w = C0 / (2 * f_hz) * math.sqrt(2 / (er + 1))

    def length_for(er_):
        ee = closed_form_eeff(er_, h, w)
        dl = 0.412 * h * (ee + 0.3) * (w / h + 0.264) / ((ee - 0.258) * (w / h + 0.8))
        return C0 / (2 * f_hz * math.sqrt(ee)) - 2 * dl, ee, dl

    length, eeff, dl = length_for(er)

    def resonance(er_):
        ee = closed_form_eeff(er_, h, w)
        dl_ = 0.412 * h * (ee + 0.3) * (w / h + 0.264) / ((ee - 0.258) * (w / h + 0.8))
        return C0 / (2 * (length + 2 * dl_) * math.sqrt(ee))

    bw = 3.77 * (er - 1) / er ** 2 * (w / length) * (h / lam0)
    q_rad = 1 / (math.sqrt(2) * bw)
    q_d = 1 / tand
    q_c = h * math.sqrt(math.pi * f_hz * MU0 * sigma)
    efficiency = (1 / q_rad) / (1 / q_rad + 1 / q_d + 1 / q_c)
    out = {"label": "SANITY CHECK ONLY: not a design value; HFSS optimises the patch later",
           "construction": key, "w_patch_m": w, "l_patch_m": length, "eeff": eeff,
           "fractional_bandwidth_vswr2": bw, "radiation_efficiency": efficiency,
           "q_rad": q_rad, "q_d": q_d, "q_c": q_c, "lambda0_m": lam0}
    b = st.tolerances[key]["rf_dielectric_permittivity"]
    if b.bounded:
        lo, hi = b.interval(er)
        out["resonance_shift_for_dk_bounds"] = (resonance(hi) / f_hz - 1, resonance(lo) / f_hz - 1)
    out["board_length_estimate_m"] = 3 * SPACING_FOR_SIZE_CHECK_M + w + 2 * 6 * h + 2 * 0.01
    return out


